def tool_index(registered: list[dict]) -> dict[str, dict]:
    return {
        t["function"]["name"]: t for t in registered
        if (t.get("function") or {}).get("name")
    }

def list_catalog(registered: list[dict]) -> str:
    catalog = [
        {
            "name": t["function"]["name"],
            "purpose": str(t["function"].get("description") or "").strip()[:150],
        }
        for t in registered
    ]
    return json.dumps({"tools": catalog, "instructions": "Вызови get_tool_instructions перед первым использованием инструмента."}, ensure_ascii=False)

def instructions_for(name: str, registered: list[dict], detail: str = "standard") -> str:
    t = tool_index(registered).get(name)
    if t is None:
        return "❌ Инструмент недоступен на текущем тарифе или не зарегистрирован. Вызови list_tools."
    fn = t["function"]
    requested_detail = str(detail or "standard").strip().lower()
    if requested_detail not in {"compact", "standard", "full"}:
        requested_detail = "standard"

    variants = INSTRUCTION_VARIANTS.get(name) or {}
    if variants:
        instructions = (
            variants.get(requested_detail)
            or variants.get("standard")
            or next(iter(variants.values()))
        )
        available_levels = [level for level in ("compact", "standard", "full") if level in variants]
    else:
        instructions = INSTRUCTIONS.get(
            name,
            "Выполни только описанное действие по явно указанным аргументам.",
        )
        available_levels = ["standard"]
        requested_detail = "standard"

    return json.dumps({
        "tool_name": name,
        "instruction_detail": requested_detail,
        "available_instruction_levels": available_levels,
        "description": fn.get("description") or "",
        "rules": BASE + " " + instructions,
        "parameters": fn.get("parameters") or {},
        "ready": True,
        "scope": "Только текущий авторизованный пользователь",
    }, ensure_ascii=False)
