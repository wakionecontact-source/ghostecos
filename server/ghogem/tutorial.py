def normalize(value: str) -> str:
    return " ".join(str(value or "").casefold().replace("ё","е").split())


def resolve_topic(value: str) -> str | None:
    q=normalize(value)
    if not q:
        return None
    if q in TOPICS:
        return q
    exact=[]
    fuzzy=[]
    for key,item in TOPICS.items():
        names=[key,item["title"],*(item.get("aliases") or [])]
        normalized=[normalize(x) for x in names]
        if q in normalized:
            exact.append(key)
        elif any(q in name or name in q for name in normalized if len(name)>=4):
            fuzzy.append(key)
    matches=exact or fuzzy
    return matches[0] if len(set(matches))==1 else None


def catalog() -> list[dict]:
    return [{"topic":key,"title":item["title"]} for key,item in TOPICS.items()]


def instructions(topic: str) -> dict:
    key=resolve_topic(topic)
    if not key:
        return {
            "ok":False,
            "error":"Не удалось однозначно определить тему.",
            "topics":catalog(),
        }
    item=TOPICS[key]
    return {
        "ok":True,
        "topic":key,
        "title":item["title"],
        "instructions":item["instructions"],
        "rule":"Объясняй своими словами и только релевантную часть. Не выдумывай UI, кнопки или ограничения вне этой инструкции.",
    }


def system_context(state: dict) -> str:
    topics=state.get("topics") or {}
    explained=list(topics.keys())
    remaining=[key for key in TOPICS if key not in topics]
    age_days=round(float(state.get("age_seconds") or 0)/86400,1)
    return (
        "\n\nTUTORIAL STATE (trusted server data):\n"
        f"• new_user={'yes' if state.get('is_new_user') else 'no'}; days_since_first_seen={age_days}.\n"
        f"• already_explained={', '.join(explained) if explained else 'none'}.\n"
        f"• not_yet_explained={', '.join(remaining[:10]) if remaining else 'none'}.\n"
        "• Не повторяй весь туториал автоматически. Если пользователь спрашивает, как работает функция/UI, "
        "сначала вызови get_tutorial_instructions для нужной темы и объясни по актуальной инструкции. "
        "После содержательного объяснения вызови mark_tutorial_explained с той же topic. "
        "Новому пользователю можно кратко подсказать ОДНУ релевантную ещё не объяснённую функцию, если это "
        "естественно помогает текущей задаче; не превращай каждый ответ в обучение."
    )
